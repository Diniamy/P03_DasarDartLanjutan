// Operator logika
void main(List<String> args) {
  print('Logika AND');
  print('true && true	: \${true && true}');
  print('true && false	: \${true && false}');
  print('false && false	: \${false && false}');
  print('false && true	: \${false && true}');

  print('\nLogika OR');
  print('true || true	: \${true || true}');
  print('true || false	: \${true || false}');
  print('false || false	: \${false || false}');
  print('false || true	: \${false || true}');

  print('\nLogika NOT');
  print('!true\t	: \${!true}');
  print('!false\t: \${!false}');
}
